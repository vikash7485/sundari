-- 1. Admin allow-list --------------------------------------------------
-- Only emails in this table can change anything on the website.
create table if not exists public.admins (
  email text primary key
);
alter table public.admins enable row level security;
-- No policies on purpose: the list can only be edited from this dashboard.

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admins
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;
grant execute on function public.is_admin() to anon, authenticated;

-- 2. Tables -------------------------------------------------------------
create table if not exists public.categories (
  slug       text primary key,
  name_en    text not null,
  name_hi    text,
  image      text,
  sort       integer not null default 100,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id               bigint generated by default as identity (start with 1001) primary key,
  title            text not null,
  title_hi         text,
  description      text,
  description_hi   text,
  category         text references public.categories (slug) on update cascade on delete set null,
  metal            text check (metal in ('gold', 'silver', 'diamond', 'fancy')),
  purity           text check (purity in ('24K', '22K', '18K', '92.5')),
  weight           numeric(10, 3) check (weight >= 0),
  price            numeric(12, 2) check (price >= 0),
  price_on_request boolean not null default false,
  occasions        text[] not null default '{}',
  in_stock         boolean not null default true,
  featured         boolean not null default false,
  images           jsonb not null default '[]'::jsonb,
  is_sample        boolean not null default false,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists products_created_idx on public.products (created_at desc);
create index if not exists products_category_idx on public.products (category);

create table if not exists public.gallery (
  id         bigint generated by default as identity primary key,
  full_url   text not null,
  thumb_url  text,
  path       text,
  thumb_path text,
  width      integer,
  height     integer,
  caption    text,
  is_sample  boolean not null default false,
  created_at timestamptz not null default now()
);

-- Key/value settings: rates, timings, why, site
create table if not exists public.settings (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz not null default now()
);

-- 3. Permissions: everyone can read, only admins can write ---------------
grant select on public.categories, public.products, public.gallery, public.settings to anon, authenticated;
grant insert, update, delete on public.categories, public.products, public.gallery, public.settings to authenticated;
grant usage, select on all sequences in schema public to authenticated;

do $$
declare t text;
begin
  foreach t in array array['categories', 'products', 'gallery', 'settings'] loop
    execute format('alter table public.%I enable row level security', t);

    execute format('drop policy if exists "Public can read" on public.%I', t);
    execute format('create policy "Public can read" on public.%I for select using (true)', t);

    execute format('drop policy if exists "Admins can insert" on public.%I', t);
    execute format('create policy "Admins can insert" on public.%I for insert to authenticated with check (public.is_admin())', t);

    execute format('drop policy if exists "Admins can update" on public.%I', t);
    execute format('create policy "Admins can update" on public.%I for update to authenticated using (public.is_admin()) with check (public.is_admin())', t);

    execute format('drop policy if exists "Admins can delete" on public.%I', t);
    execute format('create policy "Admins can delete" on public.%I for delete to authenticated using (public.is_admin())', t);
  end loop;
end $$;

-- 4. Image storage (public bucket "media") -------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('media', 'media', true, 5242880, array['image/webp', 'image/jpeg', 'image/png'])
on conflict (id) do update
  set public = true,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Media is public" on storage.objects;
create policy "Media is public" on storage.objects
  for select using (bucket_id = 'media');

drop policy if exists "Admins upload media" on storage.objects;
create policy "Admins upload media" on storage.objects
  for insert to authenticated with check (bucket_id = 'media' and public.is_admin());

drop policy if exists "Admins update media" on storage.objects;
create policy "Admins update media" on storage.objects
  for update to authenticated using (bucket_id = 'media' and public.is_admin());

drop policy if exists "Admins delete media" on storage.objects;
create policy "Admins delete media" on storage.objects
  for delete to authenticated using (bucket_id = 'media' and public.is_admin());

