// Writes supabase/seed.sql from src/data/seed.js so the live database starts
// with exactly the same categories, settings and sample items as demo mode.
// Run with: node scripts/make-seed-sql.mjs
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { SEED_CATEGORIES, DEFAULT_SETTINGS, buildSampleProducts, SAMPLE_PRODUCTS, SAMPLE_GALLERY } from '../src/data/seed.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const q = (v) => (v == null ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replaceAll("'", "''")}'`)
const json = (v) => `${q(JSON.stringify(v))}::jsonb`
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`

const products = buildSampleProducts(0)
let sql = `-- Sundari Jewellers – starting data (run once, after schema.sql).
-- Generated by scripts/make-seed-sql.mjs – sample products are marked is_sample = true
-- and can be removed in one click from the admin dashboard.

insert into public.categories (slug, name_en, name_hi, sort) values
${SEED_CATEGORIES.map((c) => `  (${q(c.slug)}, ${q(c.name_en)}, ${q(c.name_hi)}, ${c.sort})`).join(',\n')}
on conflict (slug) do nothing;

insert into public.settings (key, value) values
${Object.entries(DEFAULT_SETTINGS)
  .map(([k, v]) => `  (${q(k)}, ${json(v)})`)
  .join(',\n')}
on conflict (key) do nothing;

insert into public.products
  (title, title_hi, description, description_hi, category, metal, purity, weight, price, price_on_request, occasions, in_stock, featured, images, is_sample, created_at)
values
${products
  .map((p, i) => {
    const days = SAMPLE_PRODUCTS[i].days
    return `  (${[
      q(p.title), q(p.title_hi), q(p.description), q(p.description_hi), q(p.category), q(p.metal), q(p.purity),
      q(p.weight), q(p.price), q(p.price_on_request), arr(p.occasions), q(p.in_stock), q(p.featured), json(p.images), 'true',
      `now() - interval '${days} days'`,
    ].join(', ')})`
  })
  .join(',\n')};

insert into public.gallery (full_url, thumb_url, width, height, caption, is_sample, created_at) values
${SAMPLE_GALLERY.map((g, i) => `  (${q(g.full_url)}, ${q(g.thumb_url)}, ${g.width}, ${g.height}, ${q(g.caption)}, true, now() - interval '${i} minutes')`).join(',\n')};
`
writeFileSync(join(root, 'supabase', 'seed.sql'), sql)
console.log('Wrote supabase/seed.sql')
